import { test, expect } from '@playwright/test'
import path from 'path'

test('STEP reale: selezione gate, riempimento, pausa, reset e rimozione', async ({ page }, testInfo) => {
  await page.goto('/#/wizard')
  await page.locator('input[type="file"]').setInputFiles(path.resolve('public/sample-drawings/Frutto (1).stp'))
  await expect(page.getByText('4.326812032516769', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Avanti', exact: true }).click()
  await page.getByRole('button', { name: '4', exact: true }).click()
  await page.getByRole('combobox').selectOption('cold')
  await page.getByRole('spinbutton', { name: 'Volume materozza/canali per stampata (cm³)' }).fill('2')
  await page.getByRole('spinbutton', { name: 'Area proiettata canali (cm²)' }).fill('1')
  await page.getByRole('button', { name: 'Avanti', exact: true }).click()
  await page.getByRole('combobox').nth(0).selectOption({ label: 'ARBURG' })
  await page.getByRole('combobox').nth(1).selectOption({ label: 'Arburg 370 U' })
  await page.getByRole('combobox').nth(2).selectOption({ label: '22 mm' })
  await page.getByRole('button', { name: 'Avanti', exact: true }).click()
  await page.getByRole('button', { name: /PP \(Polipropilene\)/ }).click()
  await page.getByRole('button', { name: 'Avanti', exact: true }).click()
  await expect(page.getByText('19,307248 cm³', { exact: true })).toBeVisible()
  const simulation = page.getByRole('region', { name: 'Simulazione riempimento 3D' })
  const add = simulation.getByRole('button', { name: 'Aggiungi punto iniezione' })
  await expect(add).toBeEnabled({ timeout: 30000 })
  await expect(simulation.getByRole('button', { name: 'Avvia', exact: true })).toBeDisabled()
  const empty = await canvasSnapshot('empty')
  await add.click()
  const canvas = simulation.locator('canvas')
  const bounds = await canvas.boundingBox()
  await canvas.click({ position: { x: bounds!.width / 2, y: bounds!.height / 2 } })
  await expect(simulation.getByText('G1 selezionato')).toBeVisible()
  await simulation.getByRole('combobox', { name: 'Velocità anteprima' }).selectOption('0.25')
  await simulation.getByRole('button', { name: 'Avvia', exact: true }).click()
  await expect(simulation.getByLabel('Stato avanzamento')).not.toHaveText(/^0%/)
  await simulation.getByRole('button', { name: 'Pausa', exact: true }).click()
  const paused = await simulation.getByLabel('Stato avanzamento').textContent()
  await page.waitForTimeout(200)
  await expect(simulation.getByLabel('Stato avanzamento')).toHaveText(paused!)
  await simulation.getByRole('slider').fill('50')
  const half = await canvasSnapshot('half')
  expect(half.equals(empty), 'Il riempimento deve cambiare visibilmente il pezzo').toBe(false)
  await simulation.getByRole('slider').fill('100')
  await expect(simulation.getByRole('button', { name: 'Ripeti' })).toBeEnabled()
  const full = await canvasSnapshot('full')
  expect(full.equals(half)).toBe(false)
  await simulation.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(simulation.getByLabel('Stato avanzamento')).toHaveText(/^0%/)
  await simulation.getByRole('button', { name: 'Rimuovi tutti', exact: true }).click()
  await expect(simulation.getByRole('button', { name: 'Avvia', exact: true })).toBeDisabled()
  await expect(simulation.getByText('G1 selezionato')).toHaveCount(0)
  await expect(simulation.getByRole('alert')).toHaveCount(0)

  async function canvasSnapshot(name: string) {
    // Wait for shader uniforms to catch up with the React controls.
    await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
    return simulation.locator('canvas').screenshot({ path: testInfo.outputPath(`fill-${name}.png`) })
  }
})
